# --- GDAL / GEOS / PROJ ---
# On Windows these DLLs are not auto-discovered by GeoDjango, so we point to
# them explicitly. On Linux (Render/Railway/most hosts), GDAL/GEOS/PROJ are
# installed as system libraries and Django finds them automatically — setting
# these paths there would break things, so we only set them on Windows.
if os.name == 'nt':
    GDAL_LIBRARY_PATH = env(
        'GDAL_LIBRARY_PATH',
        default=str(BASE_DIR.parent / 'venv' / 'Lib' / 'site-packages' / 'osgeo' / 'gdal.dll'),
    )
    GEOS_LIBRARY_PATH = env(
        'GEOS_LIBRARY_PATH',
        default=str(BASE_DIR.parent / 'venv' / 'Lib' / 'site-packages' / 'osgeo' / 'geos_c.dll'),
    )
    os.environ['PROJ_LIB'] = env(
        'PROJ_LIB',
        default=str(BASE_DIR.parent / 'venv' / 'Lib' / 'site-packages' / 'osgeo' / 'data' / 'proj'),
    )

